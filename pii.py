"""発言の中の個人情報らしきものを、このPCの中だけで見つける（正規表現と辞書。AI は使わない・外へ何も送らない）。

会議の発言は名簿のように「氏名:」と書かれていないので、話し言葉で出やすい形を拾う。
「〜さん」のような呼び方がない名前は見つけられない。見落としも拾いすぎもあるので、最後は人が確かめる前提で使う。
"""
import re

_JP = "぀-ゟ゠-ヿ一-鿿々〆"
RULES = [
    ("マイナンバー", re.compile(r"(?<![\d-])\d{4}-\d{4}-\d{4}(?![\d-])|(?:個人番号|マイナンバー)[^\d]{0,15}\d{12}(?!\d)")),
    ("保険証", re.compile(r"(?:被保険者|保険証|保険者)[^\n]{0,20}?(?:記号|番号)[^\n]{0,12}?[0-9０-９A-Za-z\-‐－]{3,20}")),
    ("生年月日", re.compile(r"生年月日|誕生日|(?:昭和|平成|大正)\s?\d{1,2}年\s?\d{1,2}月\s?\d{1,2}日生")),
    ("電話", re.compile(r"(?<![\d-])0\d{1,4}[-‐－(（]\d{1,4}[-‐－)）]\d{3,4}(?![\d-])|(?<![\d-])0[789]0\d{8}(?![\d-])")),
    ("メール", re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}")),
    ("住所", re.compile(r"〒\s?\d{3}[-‐－]?\d{4}|(?:北海道|東京都|(?:京都|大阪)府|[" + _JP + r"]{2,3}県)[" + _JP + r"]{1,12}?(?:市|区|町|村|郡)[" + _JP + r"]{0,20}?\d+")),
    ("氏名", re.compile(r"(?:氏\s?名|お名前|名前)[はがを\s：:]+[" + _JP + r"]{2,8}")),
    ("識別番号", re.compile(r"(?:学籍番号|職員番号|社員番号|患者番号|受診者番号|会員番号)[^\d]{0,6}[A-Za-z0-9０-９\-]{4,15}|口座(?:番号)?[^\d\n]{0,12}[0-9０-９]{7}(?!\d)")),
    ("年齢", re.compile(r"(?<![\d.．])[0-9０-９]{1,3}\s*歳(?!\d)")),
]
# 「田中さん」「タナカ先生」の形。話し言葉では名前の前にひらがなが続くので、前の文字は漢字とカタカナだけ避ける
_HONORIFIC = re.compile(r"(?<![一-鿿々ァ-ヶー])([一-鿿々]{1,4}|[ァ-ヶー]{2,6})(?:さん|様|さま|殿|氏|先生|くん|君|ちゃん)(?![一-鿿々])")
# 名前ではない「〜さん」「〜様」「〜先生」
_NOT_NAME = {"皆", "皆様", "各位", "客", "学生", "生徒", "職員", "教員", "社員", "業者", "担当", "担当者", "委員", "委員長",
             "患者", "利用者", "事務", "事務局", "奥", "旦那", "息子", "娘", "親御", "子供", "子ども", "お子", "大将", "神", "王",
             "仕", "同", "一", "多", "模", "各", "諸", "貴", "先方", "相手", "当事者", "本人", "ご本人", "女", "男", "友人", "知人"}
# 病歴・障害・信条など。誤検出しやすいひらがなの短い語（がん・うつ）は入れない
_SENSITIVE = re.compile("|".join(map(re.escape, (
    "高血圧", "糖尿病", "癌", "腫瘍", "白血病", "うつ病", "抑うつ", "統合失調", "双極性", "適応障害", "パニック障害", "発達障害",
    "ADHD", "知的障害", "精神障害", "身体障害", "障害者手帳", "療育手帳", "要介護", "要支援", "認知症", "HIV", "エイズ", "肝炎",
    "結核", "梅毒", "性感染", "妊娠", "中絶", "流産", "不妊", "心筋梗塞", "脳梗塞", "脳出血", "てんかん", "喘息", "難病", "人工透析",
    "診断書", "診断名", "既往歴", "病名", "服薬", "休職", "傷病", "カルテ", "前科", "逮捕歴", "信仰", "支持政党", "部落",
))))


def find(text):
    """見つかった種類の一覧を返す（例: ["氏名", "電話"]）。無ければ空"""
    kinds = [k for k, rx in RULES if rx.search(text)]
    if "氏名" not in kinds and any(m.group(1) not in _NOT_NAME for m in _HONORIFIC.finditer(text)):
        kinds.append("氏名")
    if _SENSITIVE.search(text):
        kinds.append("要配慮")
    return kinds
